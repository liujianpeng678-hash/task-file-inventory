$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
$helper = Join-Path $PSScriptRoot 'move-to-trash.ps1'
$fixtureRoot = Join-Path ([IO.Path]::GetTempPath()) ('trash-bin-test-' + [Guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $fixtureRoot | Out-Null
$manifest = Join-Path $fixtureRoot 'selection.json'
$passed = 0
function Check([bool]$Condition, [string]$Message) {
    if (-not $Condition) { throw $Message }
    $script:passed += 1
}
function Select-File([string]$Relative) {
    $file = Join-Path $fixtureRoot $Relative
    return [pscustomobject]@{path=$Relative; sha256=(Get-FileHash -LiteralPath $file -Algorithm SHA256).Hash; reason='Discarded preview generated by this isolated test'; generatedThisTask=$true; unusedConfirmed=$true}
}
function Write-Selection($Files) {
    @{files=@($Files)} | ConvertTo-Json -Depth 6 | Set-Content -LiteralPath $manifest -Encoding UTF8
}
function Must-Reject([scriptblock]$Action) {
    $rejected = $false
    try { & $Action | Out-Null } catch { $rejected = $true }
    Check $rejected 'Unsafe selection was accepted.'
}

& git init --quiet $fixtureRoot
if ($LASTEXITCODE -ne 0) { throw 'Test repository init failed.' }
Set-Content -LiteralPath (Join-Path $fixtureRoot 'original.txt') -Value 'original'
Set-Content -LiteralPath (Join-Path $fixtureRoot 'final.txt') -Value 'delivered final'
Set-Content -LiteralPath (Join-Path $fixtureRoot 'preview [1].txt') -Value 'discarded preview'
& git -C $fixtureRoot add -- original.txt
if ($LASTEXITCODE -ne 0) { throw 'Test tracked-file setup failed.' }
$selected = Select-File 'preview [1].txt'
Write-Selection @($selected)
& $helper -Root $fixtureRoot -Manifest $manifest | Out-Null
Check (Test-Path -LiteralPath (Join-Path $fixtureRoot 'preview [1].txt')) 'Preview changed source.'
Check (-not (Test-Path -LiteralPath (Join-Path $fixtureRoot '.task-trash'))) 'Preview created a trash directory.'
$result = & $helper -Root $fixtureRoot -Manifest $manifest -Apply | ConvertFrom-Json
Check ($result.moved -eq 1) 'Move count is incorrect.'
Check (-not (Test-Path -LiteralPath (Join-Path $fixtureRoot 'preview [1].txt'))) 'Source was not moved.'
Check (Test-Path -LiteralPath $result.receipt) 'Recovery receipt missing.'
Check ((Test-Path -LiteralPath (Join-Path $fixtureRoot 'original.txt')) -and (Test-Path -LiteralPath (Join-Path $fixtureRoot 'final.txt'))) 'Unselected files changed.'
Must-Reject { & $helper -Root $fixtureRoot -Manifest $manifest -Apply }
& $helper -Root $fixtureRoot -Manifest $result.receipt -Restore | Out-Null
Check (-not (Test-Path -LiteralPath (Join-Path $fixtureRoot 'preview [1].txt'))) 'Restore preview changed files.'
& $helper -Root $fixtureRoot -Manifest $result.receipt -Restore -Apply | Out-Null
Check ((Get-FileHash -LiteralPath (Join-Path $fixtureRoot 'preview [1].txt')).Hash -eq $selected.sha256) 'Restored bytes differ.'
& $helper -Root $fixtureRoot -Manifest $result.receipt -Restore -Apply | Out-Null
Check (Test-Path -LiteralPath (Join-Path $fixtureRoot 'preview [1].txt')) 'Repeat restore changed files.'

Write-Selection @((Select-File 'original.txt'))
Must-Reject { & $helper -Root $fixtureRoot -Manifest $manifest -Apply }
$tampered = Select-File 'preview [1].txt'
$tampered.path = '../outside.txt'
Write-Selection @($tampered)
Must-Reject { & $helper -Root $fixtureRoot -Manifest $manifest -Apply }
$tampered.path = 'preview [1].txt'
$tampered.sha256 = '0' * 64
Write-Selection @($tampered)
Must-Reject { & $helper -Root $fixtureRoot -Manifest $manifest -Apply }
$tampered = Select-File 'preview [1].txt'
$tampered.generatedThisTask = $false
Write-Selection @($tampered)
Must-Reject { & $helper -Root $fixtureRoot -Manifest $manifest -Apply }
Write-Selection @($selected, $selected)
Must-Reject { & $helper -Root $fixtureRoot -Manifest $manifest -Apply }
Set-Content -LiteralPath (Join-Path $fixtureRoot '.env') -Value 'test fixture only'
Write-Selection @((Select-File '.env'))
Must-Reject { & $helper -Root $fixtureRoot -Manifest $manifest -Apply }
Write-Selection @($selected)
$second = & $helper -Root $fixtureRoot -Manifest $manifest -Apply | ConvertFrom-Json
Set-Content -LiteralPath (Join-Path $fixtureRoot 'preview [1].txt') -Value 'newer contents'
Must-Reject { & $helper -Root $fixtureRoot -Manifest $second.receipt -Restore -Apply }
Check ((Get-Content -LiteralPath (Join-Path $fixtureRoot 'preview [1].txt') -Raw).Trim() -eq 'newer contents') 'Restore conflict overwrote data.'
$restoreFixture = Join-Path $fixtureRoot '.task-trash/parent-fixture'
New-Item -ItemType Directory -Path (Join-Path $restoreFixture 'files/blocked') | Out-Null
Set-Content -LiteralPath (Join-Path $fixtureRoot 'blocked') -Value 'parent is a file'
Set-Content -LiteralPath (Join-Path $restoreFixture 'files/recover-good.txt') -Value 'good restore candidate'
Set-Content -LiteralPath (Join-Path $restoreFixture 'files/blocked/inner.txt') -Value 'blocked restore candidate'
$restoreFiles = @()
foreach ($relative in @('recover-good.txt', 'blocked/inner.txt')) {
    $restoreFiles += [pscustomobject]@{path=$relative; sha256=(Get-FileHash -LiteralPath (Join-Path $restoreFixture ('files/' + $relative))).Hash; reason='isolated restoration fixture'; generatedThisTask=$true; unusedConfirmed=$true}
}
$restoreReceipt = Join-Path $restoreFixture 'receipt.json'
@{root=$fixtureRoot; files=$restoreFiles} | ConvertTo-Json -Depth 6 | Set-Content -LiteralPath $restoreReceipt -Encoding UTF8
Must-Reject { & $helper -Root $fixtureRoot -Manifest $restoreReceipt -Restore -Apply }
Check (-not (Test-Path -LiteralPath (Join-Path $fixtureRoot 'recover-good.txt'))) 'Predictable blocked parent caused a partial restore.'
Check ((Test-Path -LiteralPath (Join-Path $restoreFixture 'files/recover-good.txt')) -and (Test-Path -LiteralPath (Join-Path $restoreFixture 'files/blocked/inner.txt'))) 'Blocked restore lost its recovery files.'
Set-Content -LiteralPath (Join-Path $fixtureRoot 'candidate.txt') -Value 'not selected yet'
$candidate = [pscustomobject]@{path='candidate.txt'; sha256=(Get-FileHash -LiteralPath (Join-Path $fixtureRoot 'candidate.txt')).Hash; reason='New generated candidate not yet selected for use'; generatedThisTask=$true; useDecision='unconfirmed'}
Write-Selection @($candidate)
& $helper -Root $fixtureRoot -Manifest $manifest | Out-Null
Check (Test-Path -LiteralPath (Join-Path $fixtureRoot 'candidate.txt')) 'Unconfirmed preview changed the source.'
$unconfirmedResult = & $helper -Root $fixtureRoot -Manifest $manifest -Apply | ConvertFrom-Json
Check ($unconfirmedResult.moved -eq 1 -and -not (Test-Path -LiteralPath (Join-Path $fixtureRoot 'candidate.txt'))) 'Unconfirmed generated file did not go to trash.'
$unconfirmedReceipt = Get-Content -LiteralPath $unconfirmedResult.receipt -Raw | ConvertFrom-Json
Check ($unconfirmedReceipt.files[0].useDecision -eq 'unconfirmed') 'Unconfirmed decision was not retained for recovery.'
& $helper -Root $fixtureRoot -Manifest $unconfirmedResult.receipt -Restore -Apply | Out-Null
Check ((Get-FileHash -LiteralPath (Join-Path $fixtureRoot 'candidate.txt')).Hash -eq $candidate.sha256) 'Unconfirmed file could not be restored intact.'
$candidate | Add-Member -NotePropertyName unusedConfirmed -NotePropertyValue $true
$candidate.useDecision = 'keep'
Write-Selection @($candidate)
Must-Reject { & $helper -Root $fixtureRoot -Manifest $manifest -Apply }
Check (Test-Path -LiteralPath (Join-Path $fixtureRoot 'candidate.txt')) 'Keep decision was ignored in favor of a legacy flag.'
$candidate.useDecision = 'unknown'
Write-Selection @($candidate)
Must-Reject { & $helper -Root $fixtureRoot -Manifest $manifest -Apply }
$candidate.useDecision = 'discard'
Write-Selection @($candidate)
$discardResult = & $helper -Root $fixtureRoot -Manifest $manifest -Apply | ConvertFrom-Json
Check ($discardResult.moved -eq 1) 'Explicit discard decision was rejected.'
& $helper -Root $fixtureRoot -Manifest $discardResult.receipt -Restore -Apply | Out-Null
$candidate.useDecision = 'unconfirmed'
$candidate.generatedThisTask = $false
Write-Selection @($candidate)
Must-Reject { & $helper -Root $fixtureRoot -Manifest $manifest -Apply }
[pscustomobject]@{passed=$passed; fixtureRoot=$fixtureRoot; note='Fixtures and recovery evidence retained; no real project files used.'} | ConvertTo-Json
